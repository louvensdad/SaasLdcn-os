def all_agents() -> tuple[AgentDefinition, ...]:
    return _AGENTS


def by_category(category: AgentCategory) -> tuple[AgentDefinition, ...]:
    return tuple(agent for agent in _AGENTS if agent.category == category)


def active_agents() -> tuple[AgentDefinition, ...]:
    return tuple(agent for agent in _AGENTS if agent.status == "active")


