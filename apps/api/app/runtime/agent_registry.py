"""Agent Registry -- declarative catalog of every specialized agent already
running in the LDCN OS, plus the ones named in the architecture proposal that
have no engine yet ("planned").

This module executes nothing and changes no behavior. It is a read-only
catalog over infrastructure that already exists (factory_pipeline's
AGENT_PROMPTS/PIPELINE_ORDER/_ROLE_EFFORT, the recovery triad, the quality
gate engines) so a caller can answer "which agents exist, what can each one
touch, and where is it implemented" from one place instead of grepping five
files. Phase 0 of the LDCN Multi-Agent Runtime proposal.

See docs/07-agent-runtime-conventions.md for how to add an entry. Every
`implementation` string below is `module:attribute` and is exercised by
test_agent_registry.py, which fails loudly if an entry drifts from the real
module (renamed function, deleted engine, etc.) -- this catalog is checked
against the code, never a second source of truth that can silently rot."""

